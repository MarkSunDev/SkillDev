#!/usr/bin/env python3
"""Export store-safe app icons, adaptive layers, favicons, and a mask QA sheet."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _render import (  # noqa: E402
    inline_svg,
    render_html,
    save_rgb,
    write_json,
)

ROOT = Path(__file__).resolve().parents[1]
TEMPLATES = ROOT / "assets" / "templates"
FONTS = ROOT / "assets" / "fonts"


def render_icon(
    svg: Optional[str],
    out: Path,
    size: int,
    ratio: float,
    bg: str,
    bg2: Optional[str],
    ink: str,
    angle: int,
    show_bg: bool,
    browser: Optional[str],
    wait_ms: int,
) -> Path:
    data = {
        "width": size,
        "height": size,
        "bg": bg,
        "bg2": bg2,
        "angle": angle,
        "ink": ink,
        "svg": svg,
        "mark_ratio": ratio,
        "show_bg": show_bg,
    }
    return render_html(
        TEMPLATES / "icon.html",
        data,
        out,
        size,
        size,
        transparent=not show_bg,
        wait_ms=wait_ms,
        browser=browser,
    )


def pixel_font(name: str, size: int):
    from PIL import ImageFont

    return ImageFont.truetype(str(FONTS / name), size)


def squircle_mask(size: int, power: float = 4.2):
    from PIL import Image, ImageDraw

    mask = Image.new("L", (size, size), 0)
    pixels = mask.load()
    radius = size / 2.0
    for y in range(size):
        ny = abs((y + 0.5 - radius) / radius)
        for x in range(size):
            nx = abs((x + 0.5 - radius) / radius)
            if nx ** power + ny ** power <= 1.0:
                pixels[x, y] = 255
    return mask


def mask_preview(
    icon_path: Path,
    out_path: Path,
    bg: str,
    ink: str,
    field_color: Optional[str] = None,
    mark_color: Optional[str] = None,
) -> Path:
    from PIL import Image, ImageDraw

    canvas = Image.new("RGB", (1800, 1200), bg)
    draw = ImageDraw.Draw(canvas)
    title_font = pixel_font("InstrumentSerif-Regular.ttf", 58)
    body_font = pixel_font("PublicSans.ttf", 20)
    label_font = pixel_font("PublicSans.ttf", 17)

    draw.text((80, 62), "Icon mask & small-size check", font=title_font, fill=ink)
    draw.text(
        (82, 138),
        "A store icon must survive platform masks and 16 px favicons.",
        font=body_font,
        fill=ink,
    )

    with Image.open(icon_path) as source:
        icon = source.convert("RGB")

    preview_size = 310
    boxes = [
        ("iOS squircle", "ios", 80),
        ("Circle", "circle", 520),
        ("Rounded square", "rounded", 960),
        ("Full square", "square", 1400),
    ]
    for label, kind, x in boxes:
        tile = icon.resize((preview_size, preview_size), Image.LANCZOS)
        if kind == "circle":
            mask = Image.new("L", (preview_size, preview_size), 0)
            ImageDraw.Draw(mask).ellipse((0, 0, preview_size - 1, preview_size - 1), fill=255)
            tile.putalpha(mask)
        elif kind == "rounded":
            mask = Image.new("L", (preview_size, preview_size), 0)
            ImageDraw.Draw(mask).rounded_rectangle(
                (0, 0, preview_size - 1, preview_size - 1),
                radius=int(preview_size * 0.22),
                fill=255,
            )
            tile.putalpha(mask)
        elif kind == "ios":
            tile.putalpha(squircle_mask(preview_size))
        canvas.paste(tile, (x, 220), tile if tile.mode == "RGBA" else None)
        draw.text((x, 556), label, font=label_font, fill=ink)

    draw.text((80, 660), "Small sizes", font=body_font, fill=ink)
    smalls = [128, 64, 32, 16]
    x = 80
    for small in smalls:
        tile = icon.resize((small, small), Image.LANCZOS)
        canvas.paste(tile, (x, 710))
        draw.text((x, 710 + small + 12), f"{small}px", font=label_font, fill=ink)
        x += 190

    dark_x = 900
    draw.text((dark_x, 660), "On a dark field", font=body_font, fill=ink)
    dark = Image.new("RGB", (760, 250), "#111111")
    dx = 24
    for small in (128, 64, 32, 16):
        tile = icon.resize((small, small), Image.LANCZOS)
        dark.paste(tile, (dx, 60 + (128 - small) // 2))
        dx += 180
    canvas.paste(dark, (dark_x, 690))

    chips = [("field", field_color or bg), ("ink", mark_color or ink)]
    cx = 80
    for name, color in chips:
        draw.rounded_rectangle((cx, 1040, cx + 54, 1094), radius=10, fill=color, outline=ink)
        draw.text((cx + 68, 1054), f"{name} {color}", font=label_font, fill=ink)
        cx += 320
    draw.text(
        (80, 1135),
        "Generated by brand-store-assets. Preview only; do not upload this sheet.",
        font=label_font,
        fill=ink,
    )

    out_path.parent.mkdir(parents=True, exist_ok=True)
    canvas.save(out_path, "PNG", optimize=True)
    return out_path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("logo", type=Path, help="SVG logo mark; may use currentColor or brand colors")
    parser.add_argument("--mono-logo", type=Path, default=None,
                        help="One-color SVG used only for the Android monochrome layer")
    parser.add_argument("--out", type=Path, default=Path.cwd() / "icons")
    parser.add_argument("--bg", default="#3C2634", help="Icon field color")
    parser.add_argument("--bg2", default=None, help="Optional second gradient color")
    parser.add_argument("--ink", default="#F7F4ED", help="Logo color on the icon")
    parser.add_argument("--angle", type=int, default=135)
    parser.add_argument("--mark-ratio", type=float, default=0.62)
    parser.add_argument("--preset", choices=("store", "all"), default="store")
    parser.add_argument("--transparent-play-icon", action="store_true")
    parser.add_argument("--no-preview", action="store_true")
    parser.add_argument("--browser", default=None)
    parser.add_argument("--wait-ms", type=int, default=4000)
    args = parser.parse_args()

    logo = args.logo.resolve()
    if not logo.is_file() or logo.suffix.lower() != ".svg":
        print(f"ERROR: logo must be an SVG file: {logo}", file=sys.stderr)
        return 2
    mono_logo = args.mono_logo.resolve() if args.mono_logo else logo
    if not mono_logo.is_file() or mono_logo.suffix.lower() != ".svg":
        print(f"ERROR: --mono-logo must be an SVG file: {mono_logo}", file=sys.stderr)
        return 2
    if args.mono_logo is None and re.search(
        r'(?:fill|stroke)\s*=\s*"#', logo.read_text(encoding="utf-8")
    ):
        print(
            "WARN: the logo uses hardcoded colors; pass --mono-logo for a one-color themed icon",
            file=sys.stderr,
        )
    if not (0.35 <= args.mark_ratio <= 0.80):
        print("ERROR: --mark-ratio must be between 0.35 and 0.80", file=sys.stderr)
        return 2

    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    svg = inline_svg(logo, args.ink)
    white_svg = inline_svg(mono_logo, "#FFFFFF")
    outputs: List[Dict[str, Any]] = []

    def add(path: Path, purpose: str, alpha: bool, width: int, height: int) -> None:
        outputs.append(
            {
                "file": path.name,
                "purpose": purpose,
                "width": width,
                "height": height,
                "alpha": alpha,
                "bytes": path.stat().st_size if path.exists() else 0,
            }
        )

    # iOS / App Store master: full-bleed RGB, no rounded corners, no alpha.
    ios_master = render_icon(
        svg, out / "_ios-master.png", 1024, args.mark_ratio, args.bg, args.bg2,
        args.ink, args.angle, True, args.browser, args.wait_ms,
    )
    ios_path = out / "icon-ios-1024.png"
    save_rgb(ios_master, ios_path)
    add(ios_path, "App Store icon 1024x1024 (no alpha)", False, 1024, 1024)

    # Google Play store icon: 512x512, 32-bit PNG with alpha channel, <= 1 MB.
    play_master = render_icon(
        svg, out / "_play-master.png", 1024, args.mark_ratio, args.bg, args.bg2,
        args.ink, args.angle, not args.transparent_play_icon, args.browser, args.wait_ms,
    )
    play_path = out / "icon-play-512.png"
    from PIL import Image

    with Image.open(play_master) as source:
        play = source.convert("RGBA").resize((512, 512), Image.LANCZOS)
        play.save(play_path, "PNG", optimize=True, compress_level=9)
    add(play_path, "Google Play icon 512x512 (RGBA, full bleed)", True, 512, 512)

    # Transparent mark for showcases and adaptive icons.
    mark_path = render_icon(
        svg, out / "icon-mark-1024.png", 1024, 0.74, args.bg, None,
        args.ink, args.angle, False, args.browser, args.wait_ms,
    )
    add(mark_path, "Transparent logo mark 1024x1024", True, 1024, 1024)

    # Android adaptive icon layers: 432x432, foreground inside 66/108 safe zone.
    safe_ratio = min(args.mark_ratio, 66 / 108)
    fg_master = render_icon(
        svg, out / "_adaptive-fg-master.png", 864, safe_ratio, args.bg, None,
        args.ink, args.angle, False, args.browser, args.wait_ms,
    )
    fg_path = out / "icon-adaptive-foreground-432.png"
    with Image.open(fg_master) as source:
        source.convert("RGBA").resize((432, 432), Image.LANCZOS).save(
            fg_path, "PNG", optimize=True, compress_level=9
        )
    add(fg_path, "Android adaptive foreground 432x432 (safe zone)", True, 432, 432)

    bg_master = render_icon(
        None, out / "_adaptive-bg-master.png", 864, safe_ratio, args.bg, args.bg2,
        args.ink, args.angle, True, args.browser, args.wait_ms,
    )
    bg_path = out / "icon-adaptive-background-432.png"
    save_rgb(bg_master, bg_path, (432, 432))
    add(bg_path, "Android adaptive background 432x432", False, 432, 432)

    mono_master = render_icon(
        white_svg, out / "_mono-master.png", 864, safe_ratio, args.bg, None,
        "#FFFFFF", args.angle, False, args.browser, args.wait_ms,
    )
    mono_path = out / "icon-monochrome-432.png"
    with Image.open(mono_master) as source:
        source.convert("RGBA").resize((432, 432), Image.LANCZOS).save(
            mono_path, "PNG", optimize=True, compress_level=9
        )
    add(mono_path, "Android themed icon layer 432x432", True, 432, 432)

    if not args.no_preview:
        preview_path = mask_preview(
            ios_path,
            out / "icon-mask-preview.png",
            "#F7F4ED",
            "#1F1D1A",
            field_color=args.bg,
            mark_color=args.ink,
        )
        add(preview_path, "QA mask and small-size preview", False, 1800, 1200)

    if args.preset == "all":
        for size in (48, 72, 96, 144, 192):
            path = out / f"android-{size}.png"
            save_rgb(ios_path, path, (size, size))
            add(path, f"Android legacy icon {size}px", False, size, size)
        for size in (16, 32, 48):
            path = out / f"favicon-{size}.png"
            save_rgb(ios_path, path, (size, size))
            add(path, f"Favicon {size}px", False, size, size)
        for size in (180,):
            path = out / f"apple-touch-icon-{size}.png"
            save_rgb(ios_path, path, (size, size))
            add(path, f"Apple touch icon {size}px", False, size, size)
        for size in (192, 512):
            path = out / f"pwa-{size}.png"
            save_rgb(ios_path, path, (size, size))
            add(path, f"PWA icon {size}px", False, size, size)

    for temp in out.glob("_*-master.png"):
        temp.unlink(missing_ok=True)

    manifest = {
        "logo": str(logo),
        "mono_logo": str(mono_logo),
        "field": args.bg,
        "field2": args.bg2,
        "ink": args.ink,
        "mark_ratio": args.mark_ratio,
        "outputs": outputs,
    }
    write_json(out / "icon-manifest.json", manifest)

    for item in outputs:
        print(
            f"{item['file']}: {item['width']}x{item['height']} "
            f"alpha={item['alpha']} {item['bytes'] / 1024:.1f} KB"
        )
    print(f"wrote {out / 'icon-manifest.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
